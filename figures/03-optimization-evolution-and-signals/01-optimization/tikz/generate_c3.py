def hb_radius(r, beta):
    a1 = 1 + beta - r
    disc = a1 * a1 - 4 * beta
    if disc < 0:
        return math.sqrt(beta)
    s = math.sqrt(disc)
    return max(abs((a1 + s) / 2), abs((a1 - s) / 2))


