def armijo():
    g = g_common([2, 2]); gg = g[0] ** 2 + g[1] ** 2; f0 = 34.0; c = 0.25
    phi = lambda e: f_common([2 - e * g[0], 2 - e * g[1]])
    es = linspace(0, .15, 151)
    # acceptance interval: phi(e) <= f0 - c e gg; phi quadratic in e
    acc_end = max(e for e in linspace(0, .15, 15001) if phi(e) <= f0 - c * e * gg)
    trials = []
    for e in [1, .5, .25, .125, .0625]:
        trials.append({'eta': e, 'phi': phi(e), 'threshold': f0 - c * e * gg, 'accept': phi(e) <= f0 - c * e * gg})
    body = r"""\begin{axis}[width=86mm,height=44mm,xmin=0,xmax=.15,ymin=0,ymax=95,
  xlabel={步长 $\eta$},ylabel={目标值},legend pos=north east,
  xtick={0,.03125,.0625,.09375,.125},xticklabels={$0$,$\frac1{32}$,$\frac1{16}$,$\frac3{32}$,$\frac18$}]
"""
    body += f'\\fill[FigureGreenFill] (axis cs:0,0) rectangle (axis cs:{fmt(acc_end)},95);\n'
    body += plot([(e, phi(e)) for e in es], 'FigureInk,line width=1.1pt', r'$\varphi(\eta)=f(x-\eta\nabla f(x))$')
    body += plot([(0, f0), (f0 / gg, 0)], 'FigureMuted,dotted,line width=.8pt', r'切线 $34-1028\eta$')
