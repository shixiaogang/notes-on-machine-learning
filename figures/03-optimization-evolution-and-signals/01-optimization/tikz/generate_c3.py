def run_hb(eta, beta, T):
    xp = [2.0, 2.0]; x = [2.0, 2.0]; P = [tuple(x)]
    for _ in range(T):
        g = g_common(x)
        xn = [x[i] - eta * g[i] + beta * (x[i] - xp[i]) for i in range(2)]
        xp, x = x, xn
        P.append(tuple(x))
    return P


def run_nag(L, T):
    x = [2.0, 2.0]; y = list(x); th = 1.0; P = [tuple(x)]
    for _ in range(T):
        g = g_common(y)
        xn = [y[i] - g[i] / L for i in range(2)]
        thn = (1 + math.sqrt(1 + 4 * th * th)) / 2
        y = [xn[i] + (th - 1) / thn * (xn[i] - x[i]) for i in range(2)]
        x, th = xn, thn
        P.append(tuple(x))
    return P


