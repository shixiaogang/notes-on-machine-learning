def fmt(v):
    if v == 0:
        return '0'
    a = abs(v)
    if a < 1e-3 or a >= 1e5:
        return f'{v:.5e}'
    return f'{v:.5g}'


def coords(pts):
    out, line = [], []
    for i, (x, y) in enumerate(pts):
        line.append(f'({fmt(x)},{fmt(y)})')
        if len(line) == 6:
            out.append(' '.join(line)); line = []
    if line:
        out.append(' '.join(line))
    return '\n    '.join(out)


def plot(pts, style, legend=None):
    s = f'\\addplot[{style}] coordinates {{\n    {coords(pts)}}};\n'
    if legend is not None:
        s += f'\\addlegendentry{{{legend}}}\n'
    else:
        s = s.replace('\\addplot[', '\\addplot[forget plot,', 1)
    return s


def linspace(a, b, n):
    return [a + (b - a) * i / (n - 1) for i in range(n)]


def ellipse(cx, cy, rx, ry, n=90, rot=None):
    pts = []
    for i in range(n + 1):
        t = 2 * math.pi * i / n
        x, y = rx * math.cos(t), ry * math.sin(t)
        if rot is not None:
            (a, b), (c, d) = rot
            x, y = a * x + b * y, c * x + d * y
        pts.append((cx + x, cy + y))
    return pts


def quad_levels(a, b, levels, cx=0.0, cy=0.0, style='FigureGrid,line width=.6pt'):
    """Level sets of (a (x-cx)^2 + b (y-cy)^2)/2 = c."""
    s = ''
    for c in levels:
        s += plot(ellipse(cx, cy, math.sqrt(2 * c / a), math.sqrt(2 * c / b)), style)
    return s


def write(name, body, facts):
    d = D / name
    d.mkdir(parents=True, exist_ok=True)
    (d / 'figure.tex').write_text(f'% {facts.get("summary", name)}\n% Generated by tikz/generate_c3.py; edit the generator and rerun.\n' + HEAD + body + TAIL)
    facts = dict(facts)
    facts.update(name=name, method='TikZ/pgfplots from plain-Python sampling', generator='tikz/generate_c3.py', seed=SEED)
    (d / 'figure.json').write_text(json.dumps(facts, ensure_ascii=False, indent=2) + '\n')


def gd_path(grad, x0, eta, T):
    P = [tuple(x0)]
    x = list(x0)
    for _ in range(T):
        g = grad(x)
        x = [x[i] - eta * g[i] for i in range(len(x))]
        P.append(tuple(x))
    return P


def f_common(x):
    return 0.5 * (x[0] ** 2 + 16 * x[1] ** 2)


def g_common(x):
    return [x[0], 16 * x[1]]


