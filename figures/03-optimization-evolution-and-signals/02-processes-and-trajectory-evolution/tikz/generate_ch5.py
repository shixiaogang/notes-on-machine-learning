def hmc_leapfrog():
    def leapfrog(q, p, h, L):
        pts = [(q, p)]
        Hs = [0.5 * (q * q + p * p)]
        for _ in range(L):
            p -= 0.5 * h * q
            q += h * p
            p -= 0.5 * h * q
            pts.append((q, p))
            Hs.append(0.5 * (q * q + p * p))
        return pts, Hs

    q0, p0 = 1.2, 0.6
    H0 = 0.5 * (q0 * q0 + p0 * p0)
