def martingale_transform():
    rng = random.Random(SEED + 2)
    N, R = 200, 4000
    # one path
    s, w, S, W = 0, 0, [0], [0]
    for _ in range(N):
        h = 1 if s >= 0 else -1
        e = 1 if rng.random() < 0.5 else -1
        s += e
        w += h * e
        S.append(s)
        W.append(w)
    body = [r'\begin{axis}[name=A,width=38mm,height=30mm,xmin=0,xmax=200,ymin=-30,ymax=70,'
            r'xlabel={$n$},title={(a) 一条路径},legend style={at={(0.98,0.98)},anchor=north east}]']
    body.append(r'\addplot[draw=FigureBlue,line width=.8pt] coordinates {%s};' % coords(range(N + 1), S))
    body.append(r'\addlegendentry{游走$S_n$}')
    body.append(r'\addplot[draw=FigureGreen,line width=.8pt] coordinates {%s};' % coords(range(N + 1), W))
    body.append(r'\addlegendentry{按符号跟随}')
    body.append(r'\addplot[draw=FigureRed,line width=1pt,dashed,domain=0:60] coordinates {(0,0) (70,70)};')
    body.append(r'\addlegendentry{事后挑选}')
    body.append(r'\end{axis}')
    # many paths: mean of W_n with +-2SE
    sums = [0.0] * (N + 1)
    sq = [0.0] * (N + 1)
    for _ in range(R):
        s, w = 0, 0
        for n in range(1, N + 1):
            h = 1 if s >= 0 else -1
            e = 1 if rng.random() < 0.5 else -1
            s += e
            w += h * e
            sums[n] += w
            sq[n] += w * w
    mean = [x / R for x in sums]
    se = [math.sqrt(max(sq[n] / R - mean[n] ** 2, 0) / R) for n in range(N + 1)]
    body.append(r'\begin{axis}[at={(A.outer east)},anchor=outer west,xshift=3mm,width=38mm,height=30mm,'
                r'xmin=0,xmax=200,ymin=-2,ymax=4,xlabel={$n$},title={(b) %d条路径的平均财富},ymajorgrids,'
                r'legend style={at={(0.02,0.98)},anchor=north west}]' % R)
    xs = list(range(N + 1))
    body.append(r'\addplot[draw=FigureGreen,line width=1pt] coordinates {%s};' % coords(xs, mean))
    body.append(r'\addlegendentry{样本平均}')
    body.append(r'\addplot[draw=FigureGreen,line width=.6pt,dashed] coordinates {%s};' % coords(xs, [m + 2 * e for m, e in zip(mean, se)]))
    body.append(r'\addlegendentry{$\pm2$倍标准误}')
    body.append(r'\addplot[draw=FigureGreen,line width=.6pt,dashed,forget plot] coordinates {%s};' % coords(xs, [m - 2 * e for m, e in zip(mean, se)]))
    body.append(r'\end{axis}')
    facts = {'walk': 'fair +-1', 'predictable_bet': 'H_n=+1 if S_{n-1}>=0 else -1', 'hindsight': 'H_n=xi_n, wealth n',
             'R': R, 'seed': SEED + 2, 'mean_W200': round(mean[-1], 3), 'se_W200': round(se[-1], 3)}
    return write('dtsp-martingale-transform', '''
Fair +-1 walk S_n.  Predictable bet H_n=sign(S_{n-1}) (sign(0)=+1), wealth W_n=sum H_k xi_k.
Hindsight bet H_n=xi_n gives W_n=n.  (b) Monte Carlo mean of W_n over R paths with +-2 standard errors.''', body, facts)


def doob_decomposition():
    rng = random.Random(SEED + 3)
    N, R = 200, 4000
    s, S2 = 0, [0]
    for _ in range(N):
        s += 1 if rng.random() < 0.5 else -1
        S2.append(s * s)
    M = [S2[n] - n for n in range(N + 1)]
    acc = [0.0] * (N + 1)
    for _ in range(R):
        s = 0
        for n in range(1, N + 1):
            s += 1 if rng.random() < 0.5 else -1
            acc[n] += s * s
    mean = [a / R for a in acc]
    xs = list(range(N + 1))
    lo = min(M) - 15
    body = [r'\begin{axis}[width=80mm,height=36mm,xmin=0,xmax=200,ymin=%d,ymax=%d,'
            r'xlabel={$n$},legend style={at={(0.02,0.98)},anchor=north west},ymajorgrids]' % (lo, max(S2) + 60)]
    body.append(r'\addplot[draw=FigureBlue,line width=1pt] coordinates {%s};' % coords(xs, S2))
    body.append(r'\addlegendentry{$X_n=S_n^2$}')
    body.append(r'\addplot[draw=FigureYellow,line width=1.1pt] coordinates {(0,0) (200,200)};')
    body.append(r'\addlegendentry{漂移$A_n=n$}')
    body.append(r'\addplot[draw=FigureGreen,line width=1pt] coordinates {%s};' % coords(xs, M))
    body.append(r'\addlegendentry{鞅部分$S_n^2-n$}')
    body.append(r'\addplot[draw=FigureInk,line width=.7pt,densely dashed] coordinates {%s};' % coords(*thin(xs, mean, 100)))
    body.append(r'\addlegendentry{%d条路径的$S_n^2$平均}' % R)
    body.append(r'\end{axis}')
    facts = {'X': 'S_n^2 for fair +-1 walk', 'A_n': 'n', 'M_n': 'S_n^2-n', 'R': R, 'seed': SEED + 3,
             'mean_S200^2': round(mean[-1], 2)}
    return write('dtsp-doob-decomposition', '''
Doob decomposition of the submartingale S_n^2 (fair +-1 walk): S_n^2 = (S_n^2-n) + n.
One path plus Monte Carlo average of S_n^2 over R paths.''', body, facts)


