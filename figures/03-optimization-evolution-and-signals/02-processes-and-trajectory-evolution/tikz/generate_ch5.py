def azuma_freedman():
    n, p = 1000, 0.05
    # exact law of S_n with increments +1,-1 w.p. p/2 each, 0 w.p. 1-p
    lo = 120
    dist = {0: 1.0}
    for _ in range(n):
        new = {}
        for s, pr in dist.items():
            for d, q in ((1, p / 2), (-1, p / 2), (0, 1 - p)):
                t = s + d
                if abs(t) > lo:
                    continue
                new[t] = new.get(t, 0.0) + pr * q
        dist = new
    xs = list(range(0, 41, 1))
    tail = [sum(v for s, v in dist.items() if s >= x) for x in xs]
    az = [math.exp(-x * x / (2 * n)) for x in xs]
    fr = [math.exp(-x * x / (2 * (n * p + x / 3))) if x > 0 else 1.0 for x in xs]
    body = [r'\begin{axis}[width=60mm,height=34mm,xmin=0,xmax=40,ymode=log,ymin=1e-9,ymax=2,'
            r'xlabel={$x$},ylabel={$\mathbb P(S_n\ge x)$},ytick={1e-8,1e-6,1e-4,1e-2,1},'
            r'legend style={at={(1.02,1)},anchor=north west},ymajorgrids]']
    body.append(r'\addplot[draw=FigureYellow,line width=1.1pt,dashed] coordinates {%s};' % coords(xs, az))
    body.append(r'\addlegendentry{Azuma界}')
    body.append(r'\addplot[draw=FigureGreen,line width=1.1pt,dash dot] coordinates {%s};' % coords(xs, fr))
    body.append(r'\addlegendentry{Freedman界}')
    body.append(r'\addplot[draw=FigureBlue,line width=1.1pt] coordinates {%s};' % coords(xs, [max(t, 1e-12) for t in tail]))
    body.append(r'\addlegendentry{精确尾概率}')
    body.append(r'\end{axis}')
    facts = {'n': n, 'p_bet': p, 'increments': '+1,-1 w.p. p/2 each, 0 w.p. 1-p', 'V_n': n * p,
             'x=30': {'exact': tail[30], 'azuma': az[30], 'freedman': fr[30]},
             'x=20': {'exact': tail[20], 'azuma': az[20], 'freedman': fr[20]}}
    return write('dtsp-azuma-freedman', '''
Sparse bets: increments +1,-1 with probability 0.025 each, 0 with probability 0.95, n=1000.
Exact tail of S_n by convolution (truncated at |s|<=120, negligible mass beyond).
Azuma: exp(-x^2/(2n)) (range [-1,1]); Freedman: exp(-x^2/(2(v+x/3))), v=n p=50.''', body, facts)


def upcrossings():
    rng = random.Random(SEED + 7)
    N = 300
    a, b = -2, 4
    while True:
        s, path = 0, [0]
        for _ in range(N):
            s += 1 if rng.random() < 0.5 else -1
            path.append(s)
        # count upcrossings
        segs, state, start = [], 'wait', None
        for n, v in enumerate(path):
            if state == 'wait' and v <= a:
                state, start = 'up', n
            elif state == 'up' and v >= b:
                segs.append((start, n))
                state = 'wait'
        if 3 <= len(segs) <= 6 and max(abs(x) for x in path) < 14:
            break
    body = [r'\begin{axis}[name=A,width=40mm,height=30mm,xmin=0,xmax=300,ymin=-14,ymax=14,'
            r'xlabel={$n$},title={(a) 游走对$[-2,4]$的上穿},ytick={-2,4}]']
