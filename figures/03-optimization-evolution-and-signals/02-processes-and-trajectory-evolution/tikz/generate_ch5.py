def mean_ode_tracking():
    rng = random.Random(SEED + 15)
    A = [[0.5, -1.0], [1.0, 0.5]]
    th = [2.0, 0.0]
    N = 3000
    taus, P = [0.0], [tuple(th)]
    tau = 0.0
    for n in range(N):
        al = 0.6 / (n + 5) ** 0.75
        hx = -(A[0][0] * th[0] + A[0][1] * th[1])
        hy = -(A[1][0] * th[0] + A[1][1] * th[1])
        th = [th[0] + al * (hx + 0.8 * rng.gauss(0, 1)), th[1] + al * (hy + 0.8 * rng.gauss(0, 1))]
        tau += al
        taus.append(tau)
        P.append(tuple(th))

    def ode(t):
        r = math.exp(-0.5 * t)
        return (2 * r * math.cos(t), -2 * r * math.sin(t))

    ts = [taus[-1] * k / 300 for k in range(301)]
    od = [ode(t) for t in ts]
    xs, ys = [p[0] for p in P[:400]], [p[1] for p in P[:400]]
    tx_, ty_ = thin([p[0] for p in P[400:]], [p[1] for p in P[400:]], 400)
    xs += tx_
    ys += ty_
    body = [r'\begin{axis}[name=A,width=34mm,height=34mm,xmin=-1.6,xmax=2.4,ymin=-1.6,ymax=1.4,'
            r'xlabel={$\theta_1$},ylabel={$\theta_2$},title={(a) 平面中的迭代与平均ODE},'
            r'legend style={at={(0.02,0.98)},anchor=north west}]']
    body.append(r'\addplot[draw=FigureBlue,line width=.4pt] coordinates {%s};' % coords(xs, ys))
    body.append(r'\addlegendentry{迭代}')
    body.append(r'\addplot[draw=FigureInk,line width=1.1pt] coordinates {%s};' % coords([p[0] for p in od], [p[1] for p in od]))
    body.append(r'\addlegendentry{平均ODE}')
    body.append(r'\end{axis}')
    tx, ty = taus[:400] + thin(taus[400:], [p[0] for p in P[400:]], 400)[0], [p[0] for p in P[:400]] + thin(taus[400:], [p[0] for p in P[400:]], 400)[1]
    body.append(r'\begin{axis}[at={(A.outer east)},anchor=outer west,xshift=3mm,width=40mm,height=34mm,'
                r'xmin=0,xmax=%g,ymin=-1.2,ymax=2.2,xlabel={算法时间$\tau_n=\sum_{k<n}\alpha_k$},'
                r'ylabel={$\theta_1$},title={(b) 按算法时间对齐}]' % taus[-1])
