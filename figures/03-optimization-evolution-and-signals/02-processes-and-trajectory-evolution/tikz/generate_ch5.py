def gamblers_ruin():
    rng = random.Random(SEED + 4)
    Nb, k0 = 10, 3
    body = [r'\begin{axis}[name=A,width=36mm,height=30mm,xmin=0,xmax=60,ymin=0,ymax=10,'
            r'xlabel={$n$},ylabel={$S_{n\wedge\tau}$},title={(a) 从$3$出发、到$0$或$10$停止},ytick={0,3,10},ymajorgrids]']
    count = 0
    while count < 14:
        s, path = k0, [k0]
        while 0 < s < Nb:
            s += 1 if rng.random() < 0.5 else -1
            path.append(s)
        if len(path) > 61:
            continue
        col = 'FigureGreen' if s == Nb else 'FigureBlue'
        xs = list(range(len(path)))
        body.append(r'\addplot[draw=%s,line width=.6pt] coordinates {%s};' % (col, coords(xs, path)))
        body.append(r'\addplot[only marks,mark=*,mark size=1.1pt,%s] coordinates {(%d,%d)};' % (col, len(path) - 1, s))
        count += 1
    body.append(r'\end{axis}')
    body.append(r'\begin{axis}[at={(A.outer east)},anchor=outer west,xshift=3mm,width=36mm,height=30mm,'
                r'xmin=0,xmax=10,ymin=0,ymax=1,xlabel={起点$k$},ylabel={到达$10$的概率},title={(b) 理论值与模拟},'
                r'legend style={at={(0.02,0.98)},anchor=north west},ymajorgrids]')
    facts = {'N': Nb, 'start_a': k0, 'seed': SEED + 4, 'reps_per_k': 4000, 'sim': {}}
    for p, col, ls, mk in [(0.53, 'FigureGreen', 'dashed', 'square*'), (0.5, 'FigureBlue', 'solid', '*'),
                           (0.47, 'FigureRed', 'dash dot', 'triangle*')]:
        ks = list(range(Nb + 1))
        if p == 0.5:
            th = [k / Nb for k in ks]
        else:
            r = (1 - p) / p
            th = [(1 - r ** k) / (1 - r ** Nb) for k in ks]
        body.append(r'\addplot[draw=%s,line width=1pt,%s] coordinates {%s};' % (col, ls, coords(ks, th)))
        body.append(r'\addlegendentry{$p=%s$}' % p)
        sim = []
        for k in range(1, Nb):
            hit = 0
            for _ in range(4000):
                s = k
                while 0 < s < Nb:
                    s += 1 if rng.random() < p else -1
                hit += s == Nb
            sim.append(hit / 4000)
        body.append(r'\addplot[only marks,mark=%s,mark size=1.2pt,%s,forget plot] coordinates {%s};' % (mk, col, coords(range(1, Nb), sim)))
        facts['sim'][str(p)] = sim
    body.append(r'\end{axis}')
    return write('dtsp-gamblers-ruin', '''
Simple walk on {0,...,10}, up-probability p, stopped at 0 or 10.
(a) 14 fair paths from 3 (paths longer than 60 steps skipped for display), green = reached 10.
(b) exact P_k(hit 10): k/10 for p=1/2, (1-r^k)/(1-r^10), r=(1-p)/p otherwise; markers: 4000 simulated runs per k.''', body, facts)


