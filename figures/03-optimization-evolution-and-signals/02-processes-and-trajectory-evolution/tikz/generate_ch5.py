def simulate_two_state(rng, n, x0):
    x, out = x0, []
    for _ in range(n):
        u = rng.random()
        if x == 1:
            x = 2 if u < 0.1 else 1
        else:
            x = 1 if u < 0.2 else 2
        out.append(x)
    return out


