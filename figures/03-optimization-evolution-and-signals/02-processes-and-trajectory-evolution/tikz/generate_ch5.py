def tv_decay():
    def cycle(m, lazy):
        P = [[0.0] * m for _ in range(m)]
        for i in range(m):
            if lazy:
                P[i][i] = 0.5
                P[i][(i + 1) % m] += 0.25
                P[i][(i - 1) % m] += 0.25
            else:
                P[i][(i + 1) % m] += 0.5
                P[i][(i - 1) % m] += 0.5
        return P

    N = 150
    series = []
    for label, m, lazy, col, ls in [('惰性环$m=12$', 12, True, 'FigureGreen', 'dashed'),
                                    ('惰性环$m=24$', 24, True, 'FigurePurple', 'dash dot'),
                                    ('非惰性环$m=12$', 12, False, 'FigureRed', 'densely dotted')]:
        v = [1.0] + [0.0] * (m - 1)
        P = cycle(m, lazy)
        d = []
        for n in range(N + 1):
            d.append(0.5 * sum(abs(x - 1 / m) for x in v))
            v = vecmat(v, P)
        series.append((label, col, ls, d))
    two = [(2 / 3) * 0.7 ** n for n in range(N + 1)]
    body = [r'\begin{axis}[width=62mm,height=32mm,xmin=0,xmax=150,ymode=log,ymin=1e-6,ymax=1.5,'
            r'xlabel={步数$n$},ylabel={$d(n)$},ytick={1e-6,1e-4,1e-2,1},'
            r'legend style={at={(1.02,1)},anchor=north west},ymajorgrids]']
    body.append(r'\addplot[draw=FigureBlue,line width=1.1pt] coordinates {%s};' % coords(*thin(list(range(N + 1)), two, 80)))
    body.append(r'\addlegendentry{两状态链}')
    facts = {'two_state': 'd(n)=(2/3)0.7^n', 'cycles': {}}
    for label, col, ls, d in series:
        xs, ys = thin(list(range(N + 1)), [max(y, 1e-7) for y in d], 80)
        body.append(r'\addplot[draw=%s,line width=1pt,%s] coordinates {%s};' % (col, ls, coords(xs, ys)))
        body.append(r'\addlegendentry{%s}' % label)
        facts['cycles'][label] = {'d(10)': round(d[10], 5), 'd(50)': round(d[50], 6), 'd(150)': d[150]}
    body.append(r'\end{axis}')
    return write('dtsp-tv-decay', '''
Worst-case total variation d(n)=sup_x ||P^n(x,.)-pi||_TV (start 0 by symmetry for cycles), computed exactly.
Two-state chain: (2/3)0.7^n.  Lazy cycle: stay 1/2, each neighbour 1/4.  Non-lazy cycle m=12 is periodic (d(n)=1/2... stays large).''', body, facts)


