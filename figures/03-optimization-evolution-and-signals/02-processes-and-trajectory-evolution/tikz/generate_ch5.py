def fmt(v):
    if v == 0 or abs(v) < 1e-12:
        return '0'
    return f'{v:.5g}'


def coords(xs, ys):
    return ' '.join(f'({fmt(x)},{fmt(y)})' for x, y in zip(xs, ys))


def write(name, comment, body, facts):
    folder = D / name
    folder.mkdir(parents=True, exist_ok=True)
    head = ''.join('% ' + line + '\n' for line in comment.strip().splitlines())
    text = (head + '% Generated by generate_ch5.py; edit the generator, not this file.\n'
            + r'\begin{tikzpicture}[font=\figurefont' + FONT_MAIN + ',text=FigureInk]\n'
            + AXIS_STYLE + '\n'.join(body).strip() + '\n\\end{tikzpicture}\n')
    (folder / 'figure.tex').write_text(text)
    record = {'name': name, 'method': 'pgfplots/TikZ data generated by Python standard library',
              'generator': 'figures/03-optimization-evolution-and-signals/02-processes-and-trajectory-evolution/tikz/generate_ch5.py',
              'seed_base': SEED, 'facts': facts}
    (folder / 'figure.json').write_text(json.dumps(record, ensure_ascii=False, indent=2) + '\n')
    return folder / 'figure.tex'


