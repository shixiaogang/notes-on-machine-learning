def mh_gibbs():
    rng = random.Random(SEED + 12)
    rho = 0.95
    sd_c = math.sqrt(1 - rho * rho)

    def logp(x, y):
        return -(x * x - 2 * rho * x * y + y * y) / (2 * (1 - rho * rho))

    start = (-1.5, 1.5)
    # ellipses
    ell = []
    for c in (1, 2, 3):
        pts = []
        for k in range(121):
            t = 2 * math.pi * k / 120
