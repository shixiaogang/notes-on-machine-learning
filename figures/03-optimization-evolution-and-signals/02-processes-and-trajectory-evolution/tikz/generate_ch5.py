def thin(xs, ys, m):
    if len(xs) <= m:
        return list(xs), list(ys)
    k = max(1, len(xs) // m)
    idx = list(range(0, len(xs), k))
    if idx[-1] != len(xs) - 1:
        idx.append(len(xs) - 1)
    return [xs[i] for i in idx], [ys[i] for i in idx]


def logidx(n, m=120):
    """About m indices 1..n spaced evenly in log scale."""
    out = sorted({max(1, min(n, int(round(math.exp(math.log(n) * k / m))))) for k in range(m + 1)})
    return out


def matmul(a, b):
    n, m, p = len(a), len(b), len(b[0])
    return [[sum(a[i][k] * b[k][j] for k in range(m)) for j in range(p)] for i in range(n)]


def vecmat(v, a):
    return [sum(v[k] * a[k][j] for k in range(len(v))) for j in range(len(a[0]))]


def npdf(x, mu=0.0, var=1.0):
    return math.exp(-(x - mu) ** 2 / (2 * var)) / math.sqrt(2 * math.pi * var)


