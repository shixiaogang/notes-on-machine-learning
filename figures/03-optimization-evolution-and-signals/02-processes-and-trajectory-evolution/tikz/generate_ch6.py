def fmt(v):
    if abs(v) < 5e-5:
        return '0'
    return f'{v:.4g}'


def coords(xs, ys):
    return ' '.join(f'({fmt(x)},{fmt(y)})' for x, y in zip(xs, ys))


def write(name, comment, body):
    folder = D / name
    folder.mkdir(parents=True, exist_ok=True)
    # Axis sizes below are written as outer sizes; with "scale only axis" they are
    # converted to plot-area sizes. Small widths (arrow tips etc.) are left alone.
    def _w(m):
        v = float(m[1])
        return m[0] if v < 15 else 'width=%gmm' % (v - (14 if v >= 50 else 10))
    def _h(m):
        v = float(m[1])
        return m[0] if v < 14 else 'height=%gmm' % max(6, v - 12)
    body = re.sub(r'(?<![a-z ])width=(\d+(?:\.\d+)?)mm', _w, body)
    body = re.sub(r'(?<![a-z ])height=(\d+(?:\.\d+)?)mm', _h, body)
    body = re.sub(r'\\addplot\[draw=(Figure[A-Za-z]+)([^\]]*?mark=[^\]]*)\]',
                  lambda m: '\\addplot[draw=%s%s,mark options={draw=%s,fill=%s,solid}]' % (m[1], m[2], m[1], m[1]), body)
    head = ''.join('% ' + line + '\n' for line in comment.strip().splitlines())
    text = (head + '% Generated by generate_ch6.py; edit the generator, not this file.\n'
            + r'\begin{tikzpicture}[font=\figurefont' + FONT_MAIN + ',text=FigureInk]\n'
            + AXIS_STYLE + body.strip() + '\n\\end{tikzpicture}\n')
    (folder / 'figure.tex').write_text(text)
    return folder / 'figure.tex'


