def compensated_poisson():
    rng = random.Random(SEED + 6)
    lam, T, npaths = 2.0, 10.0, 25
    raw, comp = [], []
    for _ in range(npaths):
        t, k = 0.0, 0
        xs, ys = [0.0], [0]
        while True:
            t += rng.expovariate(lam)
            if t > T:
                break
            xs.append(t)
            ys.append(k)
            k += 1
            xs.append(t)
            ys.append(k)
        xs.append(T)
        ys.append(k)
        raw.append((xs, ys))
        comp.append((xs, [y - lam * x for x, y in zip(xs, ys)]))
