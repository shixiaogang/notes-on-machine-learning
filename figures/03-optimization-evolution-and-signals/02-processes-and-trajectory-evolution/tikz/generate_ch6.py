def em_orders():
    rng = random.Random(SEED + 12)
    mu, sig, x0, T = 2.0, 1.0, 1.0, 1.0
    levels = list(range(2, 9))
    M = 4000
    nfine = 2 ** levels[-1]
    errs = {k: 0.0 for k in levels}
    for _ in range(M):
        dw = [math.sqrt(T / nfine) * rng.gauss(0, 1) for _ in range(nfine)]
        WT = sum(dw)
        exact = x0 * math.exp((mu - sig ** 2 / 2) * T + sig * WT)
        for k in levels:
            n = 2 ** k
            h = T / n
            r = nfine // n
            x = x0
            for i in range(n):
                inc = sum(dw[i * r:(i + 1) * r])
                x = x + mu * x * h + sig * x * inc
            errs[k] += abs(exact - x)
    hs = [T / 2 ** k for k in levels]
    strong = [errs[k] / M for k in levels]
    weak = [abs(math.exp(mu * T) - (1 + mu * h) ** int(round(T / h))) for h in hs]
    c1 = strong[-1] / math.sqrt(hs[-1])
    c2 = weak[-1] / hs[-1]
    body = [r'\begin{axis}[width=90mm,height=56mm,xmode=log,ymode=log,log basis x=2,xmin=0.003,xmax=0.4,'
            r'ymin=0.01,ymax=6,xlabel={步长$h$},ylabel={终点误差},ymajorgrids,xmajorgrids,'
            r'xtick={0.00390625,0.015625,0.0625,0.25},xticklabels={$2^{-8}$,$2^{-6}$,$2^{-4}$,$2^{-2}$},'
            r'legend pos=south east]']
    body.append(r'\addplot[draw=FigureBlue,line width=1.1pt,mark=*,mark size=1.1pt] coordinates {%s};' % coords(hs, strong))
