def occupation_embedded():
    rng = random.Random(SEED + 14)
    q1, q2, T = 1.0, 2.0, 200.0
    t, s = 0.0, 1
    segs = []
    while t < T:
        e = rng.expovariate(q1 if s == 1 else q2)
        segs.append((s, t, min(t + e, T)))
        t += e
        s = 3 - s
    px, py = [0.0], [1]
    for s, a, b in segs:
        if b > 20:
            px.append(20)
            py.append(s)
            break
        px.append(b)
        py.append(3 - s)
    occ_x, occ_y, emb_x, emb_y = [], [], [], []
    time1, visits1, visits = 0.0, 0, 0
    for s, a, b in segs:
        visits += 1
        visits1 += s == 1
        if s == 1:
            for k in range(1, 5):
                tt = a + (b - a) * k / 4
                occ_x.append(tt)
                occ_y.append((time1 + (tt - a)) / tt if tt > 0 else 1)
            time1 += b - a
        else:
            occ_x.append(b)
            occ_y.append(time1 / b)
        emb_x.append(b)
        emb_y.append(visits1 / visits)
    body = []
    body.append(r'\begin{axis}[name=A,width=104mm,height=30mm,xmin=0,xmax=20,ymin=0.6,ymax=2.4,ytick={1,2},'
                r'xlabel={$t$},ylabel={状态},title={(a) 两态链：离开$1$的率为$1$，离开$2$的率为$2$}]')
    body.append(r'\addplot[const plot,draw=FigureBlue,line width=1.0pt] coordinates {%s};' % coords(px[:-1] + [20], py[:-1] + [py[-2]]))
    body.append(r'\end{axis}')
    body.append(r'\begin{axis}[name=B,at={(A.south west)},anchor=north west,yshift=-18mm,width=104mm,height=44mm,'
                r'xmin=0.5,xmax=200,xmode=log,ymin=0,ymax=1.02,xlabel={$T$（对数刻度）},ylabel={状态$1$的比例},'
                r'title={(b) 按时间累计与按跳转计数},ymajorgrids,legend style={at={(0.98,0.03)},anchor=south east},legend columns=2]')
    body.append(r'\addplot[draw=FigureBlue,line width=1.0pt] coordinates {%s};' % coords(*thin(occ_x, occ_y, 900)))
    body.append(r'\addplot[draw=FigureGreen,line width=1.0pt,const plot] coordinates {%s};' % coords(*thin(emb_x, emb_y, 600)))
    body.append(r'\addplot[draw=FigureBlue,dotted,line width=.8pt,domain=0.5:200] {2/3};')
    body.append(r'\addplot[draw=FigureGreen,dotted,line width=.8pt,domain=0.5:200] {1/2};')
    body.append(r'\legend{{$T^{-1}\int_0^T\mathbb I\{X_t=1\}\,\mathrm dt$},嵌入跳链中状态$1$的访问比例,$2/3$,$1/2$}')
    body.append(r'\end{axis}')
    comment = f'''Two-state chain, holding rate 1 in state 1 and 2 in state 2, X_0=1, horizon {T}, seed={SEED+14}.
(a) first 20 time units. (b) running occupation fraction of state 1 (blue) -> 2/3 and running fraction
of visits to state 1 in the embedded jump chain (green) -> 1/2. Final values: occupation {time1/T:.4f},
visits {visits1/visits:.4f} after {visits} sojourns.'''
    return write('ctsp-occupation-embedded', comment, '\n'.join(body))


def langevin_double_well():
    rng = random.Random(SEED + 15)
    U = lambda x: 2.0 * (x * x - 1) ** 2
    dU = lambda x: 8.0 * x * (x * x - 1)
    h, T = 2e-3, 400.0
    n = int(T / h)
    x = -1.0
    xs, ts = [], []
    bins = [0] * 60
    lo, hi = -2.0, 2.0
    for i in range(n):
        x = x - h * dU(x) + math.sqrt(2 * h) * rng.gauss(0, 1)
        if i % 100 == 0:
            ts.append(i * h)
            xs.append(x)
        j = int((x - lo) / (hi - lo) * 60)
        if 0 <= j < 60:
            bins[j] += 1
    width = (hi - lo) / 60
    dens = [b / (n * width) for b in bins]
    centers = [lo + (j + 0.5) * width for j in range(60)]
    Z = sum(math.exp(-U(lo + (k + 0.5) * 4 / 4000)) for k in range(4000)) * 4 / 4000
    crossings = sum(1 for a, b in zip(xs, xs[1:]) if a * b < 0)
    body = []
    show = [(t, v) for t, v in zip(ts, xs) if t <= 100]
    body.append(r'\begin{axis}[name=A,width=64mm,height=46mm,xmin=0,xmax=100,ymin=-2,ymax=2,xlabel={$t$},'
                r'ylabel={$X_t$},title={(a) 一条Langevin路径},ymajorgrids]')
    body.append(r'\addplot[draw=FigureBlue,line width=.4pt] coordinates {%s};' % coords([s[0] for s in show], [s[1] for s in show]))
    body.append(r'\end{axis}')
    body.append(r'\begin{axis}[name=B,at={(A.east)},anchor=west,xshift=8mm,width=40mm,height=46mm,xmin=-2,xmax=2,'
                r'ymin=0,ymax=1.25,xlabel={$x$},title={(b) 时间直方图},ymajorgrids,legend pos=north east,'
                r'legend style={font=\figurefont\fontsize{7}{8}\selectfont}]')
    body.append(r'\addplot[ybar interval,draw=FigureBlue,fill=FigureBlueFill,line width=.4pt] coordinates {%s};'
                % coords([lo + j * width for j in range(61)], dens + [dens[-1]]))
    body.append(r'\addplot[draw=FigureRed,line width=1.1pt,domain=-2:2,samples=160] {exp(-2*(x^2-1)^2)/%g};' % Z)
    body.append(r'\legend{{$[0,%d]$},$\pi\propto e^{-U}$}' % int(T))
    body.append(r'\end{axis}')
