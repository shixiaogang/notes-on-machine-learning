def brownian(rng, n, T=1.0):
    h = T / n
    s = math.sqrt(h)
    w = [0.0]
    for _ in range(n):
        w.append(w[-1] + s * rng.gauss(0, 1))
    return w


def thin(xs, ys, m):
    if len(xs) <= m:
        return xs, ys
    k = max(1, len(xs) // m)
    idx = list(range(0, len(xs), k))
    if idx[-1] != len(xs) - 1:
        idx.append(len(xs) - 1)
    return [xs[i] for i in idx], [ys[i] for i in idx]


