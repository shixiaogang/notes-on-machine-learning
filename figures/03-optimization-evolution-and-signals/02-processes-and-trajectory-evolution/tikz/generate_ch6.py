def ctmc_path():
    rng = random.Random(SEED + 5)
    Q = [[-2.0, 1.5, 0.5], [1.0, -1.0, 0.0], [0.5, 1.5, -2.0]]
    T = 12.0
    t, s = 0.0, 0
    xs, ys = [0.0], [1]
    holds = []
    while True:
        rate = -Q[s][s]
        e = rng.expovariate(rate)
        if t + e > T:
            break
        t += e
        holds.append((s + 1, round(e, 3)))
        u = rng.random() * rate
        acc = 0.0
        for j in range(3):
            if j == s:
                continue
            acc += Q[s][j]
            if u <= acc:
                s = j
                break
        xs.append(t)
        ys.append(s + 1)
    xs.append(T)
    ys.append(s + 1)
    body = r'''
\begin{scope}[shift={(0,0)},x=1mm,y=1mm,
  st/.style={circle,draw=FigureBlue,fill=FigureBlueFill,line width=.75pt,minimum size=7mm,inner sep=0pt},
  ar/.style={-{Stealth[length=1.8mm,width=1.2mm]},draw=FigureStroke,line width=.7pt},
  lb/.style={font=\figurefont\fontsize{7.5}{9}\selectfont,fill=white,inner sep=1pt}]
\node[st] (s1) at (0,22) {$1$};
\node[st] (s2) at (26,22) {$2$};
\node[st] (s3) at (13,2) {$3$};
\draw[ar] (s1) to[bend left=18] node[lb,above]{$1.5$} (s2);
\draw[ar] (s2) to[bend left=18] node[lb,below]{$1$} (s1);
\draw[ar] (s1) to[bend right=22] node[lb,left]{$0.5$} (s3);
\draw[ar] (s3) to[bend right=22] node[lb,right]{$1.5$} (s2);
\draw[ar] (s3) to[bend right=22] node[lb,above right]{$0.5$} (s1);
\node[font=\figurefont\fontsize{7.5}{9}\selectfont,anchor=north] at (13,-6) {$\bm Q=\begin{pmatrix}-2&1.5&0.5\\1&-1&0\\0.5&1.5&-2\end{pmatrix}$};
\node[font=\figurefont\fontsize{8}{10}\selectfont] at (13,33) {(a) 跳转率与生成矩阵};
\end{scope}
\begin{axis}[at={(40mm,-14mm)},anchor=south west,width=66mm,height=46mm,xmin=0,xmax=12,ymin=0.5,ymax=3.5,
  ytick={1,2,3},xlabel={$t$},ylabel={$X_t$},title={(b) 停留—跳跃路径},ymajorgrids]
\addplot[const plot,draw=FigureBlue,line width=1.1pt] coordinates {%s};
\end{axis}
''' % coords(xs, ys)
    comment = f'''Three-state continuous-time Markov chain with generator Q={Q}, X_0=1, horizon {T}, seed={SEED+5}.
Holding time in state i ~ Exp(-Q_ii); next state j != i with probability Q_ij/(-Q_ii).
(state, holding time) sequence: {holds}.'''
    return write('ctsp-ctmc-path', comment, body)


