def sa_paths():
    rng = random.Random(SEED + 17)
    mu, sig, th0, T, N, npaths = 1.0, 1.0, 0.0, 60.0, 1200, 25
    dt = T / N
    grid = [i * dt for i in range(N + 1)]
    body = [r'\begin{axis}[width=104mm,height=50mm,xmin=0,xmax=60,ymin=-1.4,ymax=3.2,xlabel={$t$},'
            r'ylabel={$\theta_t$},ymajorgrids,legend pos=north east]']
    for _ in range(npaths):
        y, vals = 0.0, [th0]
        for i in range(N):
            y += mu * dt + sig * math.sqrt(dt) * rng.gauss(0, 1)
            vals.append((th0 + y) / (1 + grid[i + 1]))
        body.append(r'\addplot[draw=FigureBlue,line width=.35pt,forget plot] coordinates {%s};' % coords(*thin(grid, vals, 300)))
    body.append(r'\addplot[draw=FigureInk,line width=1.1pt,domain=0:60,samples=100] {(%g+%g*x)/(1+x)};' % (th0, mu))
    body.append(r'\addplot[draw=FigureRed,dashed,line width=1.0pt,domain=0:60,samples=150] {(%g+%g*x)/(1+x)+2*%g*sqrt(x)/(1+x)};' % (th0, mu, sig))
    body.append(r'\addplot[draw=FigureRed,dashed,line width=1.0pt,domain=0:60,samples=150,forget plot] {(%g+%g*x)/(1+x)-2*%g*sqrt(x)/(1+x)};' % (th0, mu, sig))
