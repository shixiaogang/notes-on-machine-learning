def quadratic_variation():
    rng = random.Random(SEED + 4)
    K = 16
    n = 2 ** K
    w = brownian(rng, n)
    smooth = [math.sin(2 * math.pi * i / n) for i in range(n + 1)]
    rows = []
    for k in range(1, K + 1):
        m = 2 ** k
        step = n // m
        qv = sum((w[(i + 1) * step] - w[i * step]) ** 2 for i in range(m))
        tv = sum(abs(w[(i + 1) * step] - w[i * step]) for i in range(m))
        sq = sum((smooth[(i + 1) * step] - smooth[i * step]) ** 2 for i in range(m))
        st = sum(abs(smooth[(i + 1) * step] - smooth[i * step]) for i in range(m))
        rows.append((m, qv, tv, sq, st))
    ms = [r[0] for r in rows]
    body = []
    body.append(r'\begin{axis}[name=A,width=52mm,height=44mm,xmode=log,log basis x=2,ymode=log,'
                r'xmin=1.5,xmax=90000,ymin=1e-4,ymax=6,xlabel={分段数$n$},'
                r'title={(a) 平方增量和},ymajorgrids,xtick={2,16,128,1024,8192,65536},'
                r'xticklabels={$2^1$,$2^4$,$2^7$,$2^{10}$,$2^{13}$,$2^{16}$},legend pos=south west]')
    body.append(r'\addplot[draw=FigureBlue,line width=1.1pt,mark=*,mark size=.9pt] coordinates {%s};' % coords(ms, [r[1] for r in rows]))
    body.append(r'\addplot[draw=FigurePurple,line width=1.1pt,dashed,mark=square*,mark size=.8pt] coordinates {%s};' % coords(ms, [r[3] for r in rows]))
    body.append(r'\addplot[draw=FigureMuted,line width=.6pt,dotted,domain=1.5:90000] {1};')
    body.append(r'\legend{$\sum(\Delta W)^2$,光滑路径,$t=1$}')
